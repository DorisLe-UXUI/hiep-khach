/**
 * Kết nối PostgreSQL cho máy chủ trực tuyến: MỘT kết nối riêng, mọi việc chạy lần lượt qua một hàng đợi.
 * - Mỗi việc (một yêu cầu HTTP / một tin WS) nằm trọn trong BEGIN … COMMIT; lỗi thì ROLLBACK. Vì chỉ một việc chạy
 *   tại một thời điểm nên không có cập nhật bị mất (giống Durable Object), không cần khoá hàng hay mức cô lập cao.
 * - Mất kết nối: việc đang chạy thất bại (máy chủ trả 500 'server'), kết nối bị bỏ, việc sau tạo kết nối mới.
 *   Kết nối thất bại thì trong retryMs các việc sau thất bại ngay (không xếp hàng chờ quá hạn từng cái một).
 * - Mật khẩu chỉ đọc từ tệp PGPASSWORD_FILE (mặc định /run/secrets/pg_password), đọc lại ở mỗi lần kết nối,
 *   không bao giờ lấy từ biến môi trường PGPASSWORD và không bao giờ ghi ra nhật ký.
 */
import fs from 'node:fs';
import pg from 'pg';

/** BIGINT (int8) và COUNT(*) về số JS như node:sqlite (mọi giá trị trong bảng đều nằm trong số nguyên an toàn). */
const TYPES = { getTypeParser: (oid, fmt) => (oid === 20 && fmt !== 'binary' ? Number : pg.types.getTypeParser(oid, fmt)) };

/** Đọc mật khẩu từ tệp (bỏ dấu xuống dòng cuối). Lỗi chỉ nêu tên tệp, không bao giờ nêu nội dung. */
export function readPassword(file) {
  let s;
  try { s = fs.readFileSync(file, 'utf8'); } catch (e) { throw new Error(`không đọc được tệp mật khẩu PGPASSWORD_FILE=${file} (${e.code || 'lỗi'})`); }
  s = s.replace(/[\r\n]+$/, '');
  if (!s) throw new Error(`tệp mật khẩu PGPASSWORD_FILE=${file} rỗng`);
  return s;
}

/**
 * Cấu hình kết nối từ biến môi trường PGHOST, PGPORT, PGDATABASE, PGUSER, PGPASSWORD_FILE.
 * Đọc thử tệp mật khẩu ngay (thiếu tệp thì báo lỗi lúc khởi động). Mật khẩu là hàm: pg gọi mỗi lần kết nối
 * (đổi mật khẩu trong tệp không cần khởi động lại) và giá trị không nằm trong object cấu hình.
 */
export function pgConfig(env = process.env) {
  const file = env.PGPASSWORD_FILE || '/run/secrets/pg_password';
  readPassword(file);
  return {
    host: env.PGHOST || 'db',
    port: Number(env.PGPORT || 5432),
    database: env.PGDATABASE || 'hiepkhach',
    user: env.PGUSER || 'hiepkhach',
    password: () => readPassword(file),
  };
}
/** Mô tả kết nối để ghi nhật ký (không có mật khẩu). */
export const describe = (cfg) => `${cfg.user}@${cfg.host}:${cfg.port}/${cfg.database}`;

/** Bảng của máy chủ (tên chỉ lấy từ hằng này, không bao giờ từ dữ liệu người dùng). */
export const TABLES = ['chat', 'arena', 'market', 'wallet', 'rate', 'ipr'];
// Cùng bảng và cột như bản SQLite; mốc thời gian (ms) và mọi số nguyên là BIGINT (INTEGER của SQLite là 64 bit).
// n/lid tự tăng nhưng nhận giá trị chỉ định (nhập dữ liệu cũ giữ nguyên n/lid, sau đó đặt lại bộ đếm = lớn nhất + 1).
// JSON (snap, item, sold) giữ dạng TEXT để đọc ra đúng từng ký tự đã ghi.
export const SCHEMA = [
  'CREATE TABLE IF NOT EXISTS chat (n BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, t BIGINT, pid TEXT, name TEXT, text TEXT, extra TEXT)',
  'CREATE TABLE IF NOT EXISTS arena (pid TEXT PRIMARY KEY, name TEXT, cls TEXT, level BIGINT, power BIGINT, rating BIGINT, wins BIGINT, losses BIGINT, snap TEXT, t BIGINT, oid TEXT)',
  'CREATE TABLE IF NOT EXISTS market (lid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, pid TEXT, name TEXT, item TEXT, price BIGINT, t BIGINT)',
  'CREATE TABLE IF NOT EXISTS wallet (pid TEXT PRIMARY KEY, gold BIGINT, sold TEXT)',
  'CREATE TABLE IF NOT EXISTS rate (pid TEXT, k TEXT, t BIGINT, PRIMARY KEY (pid, k))',
  'CREATE TABLE IF NOT EXISTS ipr (ip TEXT, k TEXT, w BIGINT, n BIGINT, PRIMARY KEY (ip, k))',
  'CREATE INDEX IF NOT EXISTS arena_oid ON arena (oid)',
  'CREATE INDEX IF NOT EXISTS arena_rating ON arena (rating)',
];
// khoá tư vấn: máy chủ và công cụ nhập cùng tạo bảng một lúc thì lần lượt (CREATE … IF NOT EXISTS song song có thể lỗi)
const SCHEMA_LOCK = 0x686b6768; // 'hkgh'

/** Tạo bảng/chỉ mục nếu chưa có (chạy lại nhiều lần vẫn an toàn), trong một giao dịch riêng. */
export async function createSchema(c) {
  await c.query('BEGIN');
  try {
    await c.query('SELECT pg_advisory_xact_lock($1)', [SCHEMA_LOCK]);
    for (const q of SCHEMA) await c.query(q);
    await c.query('COMMIT');
  } catch (e) { await c.query('ROLLBACK').catch(() => {}); throw e; }
}

/** Mở một kết nối (dùng cho công cụ nhập và bài kiểm tra). */
export async function connectClient(cfg) {
  const c = new pg.Client({ ...clientOpts(), ...cfg, types: TYPES });
  c.on('error', () => {}); // lỗi kết nối đã báo qua truy vấn đang chạy
  await c.connect();
  return c;
}
const clientOpts = () => ({
  application_name: 'hiep-khach-online',
  connectionTimeoutMillis: 5000,
  query_timeout: 10000, // phía máy khách: mạng treo thì không chờ mãi
  statement_timeout: 5000, // phía máy chủ: huỷ truy vấn chạy quá lâu, kết nối vẫn dùng được
  lock_timeout: 3000, // bảng đang bị khoá (vd. đang nhập dữ liệu) thì báo lỗi thay vì chờ
  idle_in_transaction_session_timeout: 30000, // tiến trình chết giữa giao dịch: máy chủ tự nhả khoá
  keepAlive: true,
});

const TIMEOUT = /timeout/i;

export class Store {
  /**
   * cfg: cấu hình pg (pgConfig()). setup(client): chạy mỗi khi có kết nối mới (tạo bảng…).
   * retryMs: sau một lần kết nối thất bại, các việc trong khoảng này thất bại ngay. max: số việc chờ tối đa.
   */
  constructor(cfg, { setup = createSchema, retryMs = 1000, max = 2000, log = (...a) => console.error(...a) } = {}) {
    this.cfg = { ...clientOpts(), ...cfg, types: TYPES };
    this.setup = setup;
    this.retryMs = retryMs;
    this.max = max;
    this.log = log;
    this.client = null;
    this.failedAt = 0;
    this.tail = Promise.resolve();
    this.size = 0; // số việc đang chạy + đang chờ
    this.closed = false;
    this.okAt = 0; // lần cuối một việc chạy xong trên cơ sở dữ liệu (cho /healthz); 0 khi mất kết nối
    this.fullLog = 0; // lần cuối ghi nhật ký "hàng đợi đầy"
    this.fullSkipped = 0;
    this.onConnect = []; // hàm (client) chạy sau setup mỗi khi có kết nối mới (vd. tải tin kênh thế giới vào bộ nhớ)
  }

  /** Bỏ một kết nối (lỗi, quá hạn, đóng). */
  drop(c) {
    if (this.client === c) { this.client = null; this.okAt = 0; }
    c.end().catch(() => {});
  }
  async connect() {
    if (this.client) return this.client;
    if (Date.now() - this.failedAt < this.retryMs) throw new Error('db: chưa kết nối lại được');
    const c = new pg.Client(this.cfg);
    // mất kết nối khi đang rảnh: bỏ ngay để việc sau kết nối lại
    c.on('error', (e) => { this.log('db: mất kết nối:', e.message); this.drop(c); });
    c.on('end', () => { if (this.client === c) { this.client = null; this.okAt = 0; } });
    try {
      await c.connect();
      await this.setup(c);
      for (const f of this.onConnect) await f(c);
    } catch (e) {
      this.log('db: không kết nối được:', e.message); // tối đa mỗi retryMs một lần
      this.failedAt = Date.now();
      this.drop(c);
      throw e;
    }
    this.failedAt = 0;
    this.client = c;
    return c;
  }

  /**
   * Xếp fn(client) vào hàng đợi. tx=true: bọc trong BEGIN/COMMIT, lỗi thì ROLLBACK và ném lại.
   * Lời hứa chỉ thành công khi COMMIT đã xong (sự kiện phát sau đó mới đúng).
   * skip(): tới lượt mà trả true (vd. máy khách đã ngắt) thì không chạy, lỗi có e.skipped.
   * Hàng đợi đầy: từ chối ngay (lỗi có e.busy), nhật ký tối đa mỗi 10 giây một dòng.
   */
  run(fn, { tx = true, skip = null } = {}) {
    if (this.closed) return Promise.reject(new Error('db: đã đóng'));
    if (this.full()) return Promise.reject(Object.assign(new Error('db: hàng đợi đầy'), { busy: true }));
    this.size++;
    const p = this.tail.then(() => {
      if (skip?.()) throw Object.assign(new Error('db: máy khách đã ngắt'), { skipped: true });
      return this.exec(fn, tx);
    }).finally(() => { this.size--; });
    this.tail = p.catch(() => {});
    return p;
  }
  /** Hàng đợi đầy chưa; đầy thì ghi nhật ký, tối đa mỗi 10 giây một dòng (kèm số lần từ chối đã gộp). */
  full() {
    if (this.size < this.max) return false;
    const now = Date.now();
    if (now - this.fullLog >= 10000) {
      this.log(`db: hàng đợi đầy (${this.max} việc), từ chối yêu cầu` + (this.fullSkipped ? ` (+${this.fullSkipped} lần từ lần ghi trước)` : ''));
      this.fullLog = now; this.fullSkipped = 0;
    } else this.fullSkipped++;
    return true;
  }
  async exec(fn, tx) {
    const c = await this.connect();
    try {
      if (!tx) { const out = await fn(c); this.okAt = Date.now(); return out; }
      await c.query('BEGIN');
    } catch (e) { this.drop(c); throw e; } // BEGIN/truy vấn đơn lẻ không chạy được: coi như kết nối hỏng
    let committing = false;
    try {
      const out = await fn(c);
      committing = true;
      await c.query('COMMIT');
      this.okAt = Date.now();
      return out;
    } catch (e) {
      // COMMIT quá hạn phía máy khách: không biết đã ghi hay chưa (trả 500, không phát sự kiện); hiếm, người gọi ghi nhật ký
      if (committing && TIMEOUT.test(e?.message) && !e?.code) e.unknownCommit = true;
      // quá hạn phía máy khách: truy vấn cũ có thể vẫn đang chạy trên kết nối => bỏ hẳn kết nối
      if (this.client !== c || (TIMEOUT.test(e?.message) && !e?.code)) this.drop(c);
      else {
        try { await c.query('ROLLBACK'); } catch { this.drop(c); }
      }
      throw e;
    }
  }
  /** Có việc nào chạy xong trên cơ sở dữ liệu trong ms vừa qua (và chưa mất kết nối từ đó) không. */
  fresh(ms) { return !!this.client && Date.now() - this.okAt < ms; }
  /** Cơ sở dữ liệu có trả lời không (cho /healthz). */
  ping() { return this.run((c) => c.query('SELECT 1'), { tx: false }).then(() => true, () => false); }
  /** Chờ các việc đang xếp hàng rồi đóng kết nối. */
  async close() {
    if (this.closed) return;
    this.closed = true;
    await this.tail;
    if (this.client) { const c = this.client; this.client = null; await c.end().catch(() => {}); }
  }
}
